#include <iostream>
#include <cmath>//для косинуса и модуля abs
using namespace std;
int main() {
	const double PI = 3.141592653589793;//Число Пи
	double a = PI / 5.0;//начало отрезка х
	double b = PI;//конец отрезка х
	int k = 10;//количество шагов
	double h = (b - a) / k;//шаг: (конец - начало)/кол-во шагов
	int cnt = 20;//сколько членов ряда считать для sn
	double e = 0.0001;//точность для se
	//Перебираем каждое значение х
	//1е-9 не дает комп-у пропустить последнюю точку из-за округления
	for (double x = a; x <= b + 1e-9; x += h)
	{
		//способ 1: считаем сумму sn(ровно 20 членов)
		double SN = 0.0;//изначально сумма пустая и равна 0
		double sign = -1.0;//знак первого члена(минус)
		//цикл счетчик n от 1 до 20
		for (int n = 1; n <= cnt; n++)
		{
			//считаем текущий член по формуле из 14 варианта
			double an = sign * cos(n * x) / (n * n);
			SN += an;//добавляем текущий член к сумме
			sign = -sign;//меняем знак на противоположный
		}
		//способ 2: считаем сумму se(пока не достигнем точности e)
		double SE = 0.0;//изначально сумма пустая и равна 0
		int n = 1;//начинаем с 1 члена
		sign = -1.0;//изначально знак минус
		//считаем самый первый член заново
		double an = sign * cos(n * x) / (n * n);
		//пока модуль члена не меньше точности
		while (abs(an) >= e) {
			SE += an;//добавляем член в сумму
			n++;//переходим к следующему номеру
			sign = -sign;//меняем знак
			//считаем следующий член
			an = sign * cos(n * x) / (n * n);
		}
		//способ 3: считаем точное значение
		double Y = 0.25 * (x * x - (PI * PI) / 3.0);
		cout << "X=" << x
			<< "      SN=" << SN
			<< "      SE=" << SE
			<< "      Y=" << Y << endl;
	}
	return 0;
}