using namespace std;
const int N = 100;// объявляем константу N = 100 — максимальный размер массивов
//принимает матрицу a и её размер m, печатает произведение нужных столбцов
void product(int a[][N], int m)
{
    int p = 1;//начинаем с 1 (нейтральное для умножения)
    for (int j = 0; j < m; j++)// перебираем все столбцы матрицы (j — номер столбца)
    {
        if (a[0][j] > a[j][j] && a[0][j] > a[j][m - 1 - j]) //условие: первый элемент столбца больше главной И побочной диагонали
        {
            for (int i = 0; i < m; i++)
                p = p * a[i][j];// если условие выполнено — перемножаем все элементы столбца j
        }
    }
    cout << "Произведение = " << p << endl;
}

int main()
{
    setlocale(LC_ALL, "RU");
    srand(time(0));// запускаем генератор случайных чисел (time(0) даёт разное стартовое число при каждом запуске)
    //№4
    int n;// объявляем переменную n — реальную длину одномерного массива
    cout << "n = ";
    cin >> n;// просим пользователя ввести n и читаем его с клавиатуры
    int a[N];// объявляем одномерный массив a на N = 100 элементов
    for (int i = 0; i < n; i++)
        a[i] = rand() % 21 - 10; // заполняем первые n элементов случайными числами от −10 до 10
    cout << "Исходный: ";
    for (int i = 0; i < n; i++)
        cout << a[i] << " ";// выводим каждый элемент массива через пробел
    cout << endl;
    // переворот
    for (int i = 0; i < n / 2; i++)// идём по первой половине массива (до середины)
    {
        int t = a[i];// запоминаем левый элемент во временную переменную t
        a[i] = a[n - 1 - i];// на место левого ставим симметричный ему с конца
        a[n - 1 - i] = t;// на место правого ставим сохранённый левый
    }

    // если нечётное — удалить средний
    if (n % 2 != 0)// проверяем: нечётное ли количество элементов
    {
        for (int i = n / 2; i < n - 1; i++)
            a[i] = a[i + 1];// сдвигаем все элементы после среднего на одну позицию влево
        n--;// уменьшаем длину массива на 1 (удалили средний элемент)
    }
    cout << "После переворота: ";
    for (int i = 0; i < n; i++)
        cout << a[i] << " ";// выводим элементы уже новой длины
    cout << endl;
    // добавить 3 элемента в начало: M[I+10]-2
    int x = a[10] - 2;// для I = 0 берём a[10] и вычитаем 2
    int y = a[11] - 2;// для I = 1 берём a[11] и вычитаем 2
    int z = a[12] - 2;// для I = 2 берём a[12] и вычитаем 2
    for (int i = n - 1; i >= 0; i--)
        a[i + 3] = a[i];// сдвигаем массив вправо на 3 позиции (с конца, чтобы не затереть данные)
    a[0] = x;
    a[1] = y;
    a[2] = z; // записываем три сохранённых значения в первые ячейки
    n += 3;// увеличиваем длину массива на 3

    cout << "После добавления: ";
    for (int i = 0; i < n; i++)
        cout << a[i] << " ";// выводим итоговый массив
    cout << endl;

    //№5
    int m;//m — размер квадратной матрицы
    cout << "m = ";
    cin >> m;
    int b[N][N];// объявляем двумерный массив b на N × N = 100 × 100
    for (int i = 0; i < m; i++)// перебираем строки от 0 до m-1
        for (int j = 0; j < m; j++)// перебираем столбцы от 0 до m-1
            b[i][j] = rand() % 21 - 10;// заполняем элемент случайным числом от −10 до 10
    cout << "Матрица:" << endl;
    for (int i = 0; i < m; i++)// внешний цикл — по строкам
    {
        for (int j = 0; j < m; j++)
            cout << b[i][j] << "\t";// печатаем элемент строки и табуляцию
        cout << endl;
    }
    product(b, m);// вызываем функцию product, передаём ей матрицу b и её размер m
    return 0;           
}