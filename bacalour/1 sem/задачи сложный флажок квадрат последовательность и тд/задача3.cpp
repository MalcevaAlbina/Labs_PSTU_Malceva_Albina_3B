/*
Сосчитать сумму проивзедений Дано n
S = 1*2 + 2*3*4 + 3*4*5*6...
n*(n+1)*(n+2)...* 2n
1.Сумма состоит из n слагаемых каждое слагаемое произведение
2.Внешний по i суммирование
Внутренний по j умножение
Первый элемент которого равен i
Последний элемент которого равен 2i
3.Замечена закономерность что последний элемент\
каждого произведения равен 2i
*/
#include <iostream>
using namespace std;
int main()
{
	int n, i, j, a, s = 0;
	cin >> n;
	for (i = 1; i <= n; ++i)
	{
		a = 1;
		for (j = i; j <= 2 * i; ++j)
		{
			a *= j;
			
		}
		s += a;
	}
	cout << s;
	return 0;
}