#include <iostream>
using namespace std;
int main() 
{
	int a = 4, b = 9;
	int* p = &a;//указатель p хранит адрес переменной а
	int* q = p;//указательь q копирует адрес из p(теперь оба указывают на а)
	int& r = *p;//Ссылка r привязывается к значению по адресу p тоесть а
	p = &b;//теперь P хранит адрес переменной b
	*q += *p;//*q(a) складываем с *p(b) а = 4+9 = 13
	*p = r - 3;//*p(это b) = значение r (это а) - 3 b = 10
	q = p;//теперь q тоже хранит адрес b (оба указателя на b)
	*q += r;//*q(b) складываем со ссылкой r (это а, равно 13) b = 10 + 13 = 23
	cout << a << ' ' << b << ' ' << r;
	return 0;
}