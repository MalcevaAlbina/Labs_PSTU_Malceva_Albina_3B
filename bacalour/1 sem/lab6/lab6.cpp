#include <iostream>
using namespace std;

int main()
{
    char s[256]; // Создаём массив для хранения строки
    cin.getline(s, 256); // Вводим строку с клавиатуры
    int i = 0; // Начинаем с первого символа строки
    while (s[i] != '\0') // Пока не конец строки
    {
        while (s[i] == ' ') // Пока встречаются пробелы
            i++; // Переходим к следующему символу
        int a = i; // Запоминаем начало слова
        while (s[i] != ' ' && s[i] != '\0') // Пока не встретили пробел или конец строки
            i++; // Переходим к следующему символу
        int b = i - 1; // Запоминаем конец слова
        for (int j = a; j <= b; j++) // Перебираем символы слова
        {
            if (s[j] >= '0' && s[j] <= '9') // Проверяем, является ли символ цифрой
            {
                for (int k = j + 1; k <= b; k++) // Перебираем символы после текущего
                {
                    if (s[k] >= '0' && s[k] <= '9' && s[j] < s[k]) // Если следующая цифра больше текущей
                    {
                        char t = s[j]; // Сохраняем текущую цифру
                        s[j] = s[k]; // Меняем цифры местами
                        s[k] = t; // Ставим сохранённую цифру на место второй
                    }
                }
            }
        }
    }

    cout << s; // Выводим изменённую строку

    return 0;
}
